const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { harness } = require('./harness.cjs')
async function main() {
 const h = await harness()
 let checks = 0
 const post = async (type, input, expected = 200) => {
   const r = await h.request('POST', 'https://example.test/api/admin/revenue', { type, request_id: randomUUID(), ...input })
   const body = await r.json()
   assert.equal(r.status, expected, JSON.stringify(body)); checks++
   return body
 }
 try {
   const { account_id } = await post('create', { company_name: 'Test El AB', org_number: '5561001001' })
   const detail = async () => (await h.request('GET', `https://example.test/api/admin/revenue?account_id=${account_id}`)).json()
   let d = await detail()
   const qualification = { account_id, version: d.account.version, employee_count: 8, swedish_trade: true, confirmed_pain: true, confirmed_growth: true, warm_relationship: true, confirmed_budget: true, evidence: 'Samtal med ägaren: åtta anställda, budget och växande orderbok.', observed_at: '2026-01-01', website: 'https://example.test', industry: 'El', city: 'Uppsala' }
   await post('qualify', { ...qualification, evidence: '' }, 400)
   await post('qualify', { ...qualification, employee_count: -1 }, 400)
   await post('qualify', qualification)
   d = await detail()
   assert.equal(d.account.total_score, 80)
   assert.equal(d.account.last_contact_at, null)
   await post('qualify', qualification, 409)
   await post('contact', { account_id, name: 'Ägaren', email: 'owner@example.test', phone: '0701001001', contact_basis: 'warm_intro' })
   d = await detail()
   const start = { account_id, version: d.account.version, contact_id: d.contacts[0].id, due_at: new Date(Date.now() - 60000).toISOString() }
   const request_id = randomUUID()
   await post('sequence_start', { ...start, request_id })
   await post('sequence_start', { ...start, request_id })
   d = await detail()
   assert.equal(d.sequences.length, 1)
   assert.equal(d.account.last_contact_at, null)
   const current = () => ({ account_id, version: d.account.version, sequence_id: d.sequences[0].id })
   await post('sequence_complete', { ...current(), outcome: 'no_response', summary: 'Ringde' }, 400)
   const approveId = randomUUID()
   await post('sequence_approve', { ...current(), body: 'Granskat samtalsunderlag', request_id: approveId })
   d = await detail()
   assert.equal(d.activities.filter(a => a.activity_type !== 'note').length, 0)
   const complete = { ...current(), outcome: 'no_response', summary: 'Ringde, ingen svarade.', request_id: randomUUID() }
   await post('sequence_complete', complete)
   await post('sequence_complete', complete)
   d = await detail()
   assert.equal(d.sequences[0].step, 1)
   assert.equal(d.sequences[0].status, 'active')
   assert.equal(d.activities.filter(a => a.activity_type === 'call').length, 1)
   assert.equal(d.account.next_action, 'Följ upp med ett kort mejl')
   const due = new Date(d.sequences[0].due_at)
   const day = new Intl.DateTimeFormat('en-US', { timeZone: 'Europe/Stockholm', weekday: 'short' }).format(due)
   assert(!['Sat','Sun'].includes(day))
   await post('sequence_approve', { ...current(), body: 'Mejlunderlag' })
   await post('sequence_complete', { ...current(), outcome: 'no_response', summary: 'För tidigt' }, 400)
   await post('activity', { account_id, activity_type: 'email', outcome: 'replied', summary: 'Kunden svarade.' })
   d = await detail()
   assert.equal(d.sequences[0].status, 'stopped')
   await post('sequence_approve', { ...current(), body: 'Mejlunderlag' }, 409)
   await post('sequence_start', { ...start, version: d.account.version })
   d = await detail()
   await post('next', { account_id, version: d.account.version, status: 'conversation', contact_state: 'active', next_action: 'Boka möte', next_action_at: new Date().toISOString() })
   d = await detail()
   assert(d.sequences.every(s => s.status === 'stopped'))
   await post('sequence_start', { ...start, version: d.account.version })
   d = await detail()
   await h.db.query('insert into gtm_suppression(email) values($1)', ['owner@example.test'])
   await post('sequence_approve', { ...current(), body: 'Spärrat' }, 400)
   await h.db.query('delete from gtm_suppression where email=$1', ['owner@example.test'])
   await post('sequence_approve', { ...current(), body: 'Granskat' })
   await post('sequence_complete', { ...current(), outcome: 'opt_out', summary: 'Bad oss sluta ringa.' })
   d = await detail()
   assert.equal(d.account.contact_state, 'opted_out')
   assert.equal(d.account.next_action_at, null)
   await post('sequence_start', { ...start, version: d.account.version }, 409)
   const managerMetrics = (await (await h.request('GET', 'https://example.test/api/admin/revenue')).json()).metrics
   assert.equal(managerMetrics.contacted_30d, 1)
   assert.equal(managerMetrics.active_sequences, 0)
   assert.equal(managerMetrics.unqualified, 0)
   const exportResponse = await h.request('GET', 'https://example.test/api/admin/revenue?export=crm')
   assert.equal(exportResponse.status, 200)
   assert((await exportResponse.text()).includes(account_id))
   const { crmExport } = h.load('lib/revenue/export.ts')
   assert(crmExport([{ id: 'stable-id', company_name: '=HYPERLINK("unsafe")' }]).includes("'="))
   assert(crmExport([{ id: 'stable-id', company_name: 'Firma, "El"' }]).includes('"Firma, ""El"""'))
   // Complete a separate three-step journey, simulating elapsed time in the database.
   const second = await post('create', { company_name: 'Fullfölj El AB', org_number: '5561001002' })
   const secondDetail = async () => (await h.request('GET', `https://example.test/api/admin/revenue?account_id=${second.account_id}`)).json()
   await post('contact', { account_id: second.account_id, name: 'Kontakt två', email: 'two@example.test', phone: '0702002002', contact_basis: 'inbound' })
   let d2 = await secondDetail()
   await post('sequence_start', { account_id: second.account_id, version: d2.account.version, contact_id: d2.contacts[0].id, due_at: new Date(Date.now()-60000).toISOString() })
   for (let step=0; step<3; step++) {
     d2 = await secondDetail()
     const input = { account_id: second.account_id, sequence_id: d2.sequences[0].id, version: d2.account.version }
     await h.db.query("update revenue_sequences set due_at=now()-interval '1 minute' where id=$1", [d2.sequences[0].id])
     await post('sequence_approve', { ...input, body: 'Granskat steg '+step })
     await post('sequence_complete', { ...input, outcome: 'no_response', summary: 'Genomfört steg '+step })
   }
   d2 = await secondDetail()
   assert.equal(d2.sequences[0].status, 'completed')
   assert.equal(d2.account.next_action_at, null)
   assert.equal(d2.activities.filter(a=>a.activity_type==='email').length, 1)
   assert.equal(d2.activities.filter(a=>a.activity_type==='call').length, 2)
   h.ctx.manager = false; h.ctx.email = 'other@handymate.se'
   await post('qualify', { ...qualification, version: d.account.version }, 404)
   await post('sequence_complete', complete, 404)
   const sellerMetrics = (await (await h.request('GET', 'https://example.test/api/admin/revenue')).json()).metrics
   assert.equal(sellerMetrics.contacted_30d, 0)
   assert.equal(sellerMetrics.sources.length, 0)
   const emptyExport = await (await h.request('GET', 'https://example.test/api/admin/revenue?export=crm')).text()
   assert(!emptyExport.includes(account_id))
   const permissions = (await h.db.query("select has_table_privilege('authenticated','revenue_sequences','SELECT') as readable, has_function_privilege('anon','revenue_sales_command(uuid,text,boolean,uuid,text,jsonb)','EXECUTE') as executable")).rows[0]
   assert.deepEqual(permissions, { readable: false, executable: false })
   h.ctx.manager = true
   await h.db.exec("insert into revenue_accounts(company_name,owner_email) select 'Exportprov '||n,'a@handymate.se' from generate_series(1,60) n")
   const fullExport = await (await h.request('GET', 'https://example.test/api/admin/revenue?export=crm')).text()
   assert(fullExport.includes('Exportprov 60'))
   await h.db.exec("insert into revenue_accounts(company_name,owner_email) select 'Exporttak '||n,'a@handymate.se' from generate_series(1,5000) n")
   const capped = await h.request('GET', 'https://example.test/api/admin/revenue?export=crm')
   assert.equal(capped.status, 400)
   assert((await capped.json()).error.includes('5 000'))
   console.log(`PASS ${checks} handler checks plus persisted scoring, sequence, metrics, replay, suppression and permissions assertions`)
 } finally { await h.db.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
