// Run with PGLITE_MODULE pointing at an installed @electric-sql/pglite module.
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite')
const fs=require('node:fs'),assert=require('node:assert/strict')
;(async()=>{
const db=new PGlite()
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create table business_config(business_id text primary key); insert into business_config values ('a'),('b'); create table invoice(invoice_id text primary key,business_id text,fortnox_document_number text);`)
await db.exec(fs.readFileSync('sql/20260914072732_fortnox_sync_locks.sql','utf8'))
await db.exec('set role service_role')
const call=async(b,owner,renew=false)=>(await db.query('select claim_fortnox_operation($1,$2,$3,$4) as ok',[b,'oauth',owner,renew])).rows[0].ok
const one='00000000-0000-0000-0000-000000000001',two='00000000-0000-0000-0000-000000000002'
assert.equal(await call('a',one),true)
assert.equal(await call('a',two),false)
assert.equal(await call('b',two),true)
assert.equal(await call('a',one,true),true)
assert.equal(await call('a',two,true),false)
await db.exec("update fortnox_operation_lock set expires_at=now()-interval '1 second' where business_id='a'")
assert.equal(await call('a',one,true),false)
assert.equal(await call('a',two),true)
await db.query('delete from fortnox_operation_lock where business_id=$1 and owner=$2',['a',one])
assert.equal(await call('a',one),false)
await db.exec('reset role; set role authenticated')
await assert.rejects(call('a',one))
await assert.rejects(db.query('select * from fortnox_operation_lock'))
await db.exec('reset role')
await db.exec("insert into invoice values ('i1','a','1'),('i2','b','1')")
await assert.rejects(db.exec("insert into invoice values ('i3','a','1')"))
await db.close()
console.log('PASS PostgreSQL lease acquisition, exclusion, renewal, expiry, stale-owner release, tenant separation, RLS privileges and invoice uniqueness')
})().catch(e=>{console.error(e);process.exitCode=1})
